// lint-staged (the pre-commit hook, .husky/pre-commit): oxlint and oxfmt on the staged files.

/**
 * Files oxfmt will not format. Keep in sync with `ignorePatterns` in .oxfmtrc.json.
 *
 * oxfmt exits non-zero when every file handed to it is excluded by its own ignore rules, and
 * lint-staged can put an ignored file alone in a chunk, so they are filtered out here first.
 *
 * @param {string} file
 */
const isOxfmtIgnored = (file) => {
  const p = file.replace(/\\/g, '/');
  const base = p.slice(p.lastIndexOf('/') + 1);
  return (
    /(^|\/)(dist|node_modules|target)\//.test(p) ||
    /(^|\/)packages\/(cli-[^/]+|pxsig\/dashboard|pxsig\/docs)\//.test(p) ||
    base === 'pnpm-lock.yaml' ||
    /^tsconfig.*\.json$/.test(base) ||
    base.endsWith('.tsbuildinfo') ||
    p.includes('/.pxsig/') ||
    base === 'pxsig.config.json' ||
    base === 'pxsig.workspace.json' ||
    p.endsWith('CHANGELOG.md') ||
    // Generated by `pnpm ui:docs` and `pnpm ui:lock`, which own their formatting.
    /(^|\/)packages\/dashboard\/src\/ui\/(manifest|contract-lock)\.json$/.test(p) ||
    /(^|\/)packages\/dashboard\/fixtures\/screens\.json$/.test(p) ||
    p.endsWith('docs/ui/features.md') ||
    p.includes('docs/ui/catalog/') ||
    // Read and hashed by their text (ui-tools.mjs) and compared word for word (agents.test.mjs).
    /(^|\/)packages\/dashboard\/src\/ui\/(contract|tokens)\.ts$/.test(p) ||
    p.endsWith('docs/agents.md')
  );
};

/**
 * Files oxlint will not lint. Keep in sync with `ignorePatterns` in .oxlintrc.json.
 *
 * oxlint exits non-zero ("No files found to lint") when every file handed to it is ignored, so a
 * commit of only `.d.ts` files would always fail; they are filtered out here first, as for oxfmt.
 *
 * @param {string} file
 */
const isOxlintIgnored = (file) => {
  const p = file.replace(/\\/g, '/');
  return (
    /(^|\/)(node_modules|dist|target|storybook-static)\//.test(p) ||
    p.endsWith('.d.ts') ||
    /(^|\/)packages\/(cli-[^/]+|pxsig\/dashboard|pxsig\/docs)\//.test(p)
  );
};

/**
 * Quote with forward slashes so the command is safe under the sh-based git hook.
 * @param {string} f
 */
const quote = (f) => `"${f.replace(/\\/g, '/')}"`;

/** @param {string[]} files */
const oxlint = (files) => {
  const targets = files.filter((f) => !isOxlintIgnored(f));
  return targets.length ? [`pnpm exec oxlint --type-aware ${targets.map(quote).join(' ')}`] : [];
};

/** @param {string[]} files */
const oxfmt = (files) => {
  const targets = files.filter((f) => !isOxfmtIgnored(f));
  return targets.length ? [`pnpm exec oxfmt ${targets.map(quote).join(' ')}`] : [];
};

export default {
  '*.{ts,tsx,js,jsx,mjs,cjs}': (/** @type {string[]} */ files) => [
    ...oxlint(files),
    ...oxfmt(files),
  ],
  '*.{json,md,yaml,yml,css,html}': oxfmt,
  // rustfmt on the staged files only (`cargo fmt --all` rewrote unstaged ones too). It still
  // formats the out-of-line modules a staged file declares: skipping them is unstable rustfmt.
  // The edition matches Cargo.toml's `workspace.package.edition`.
  '*.rs': (/** @type {string[]} */ files) => `rustfmt --edition 2021 ${files.map(quote).join(' ')}`,
};
