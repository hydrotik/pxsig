#!/usr/bin/env node
/**
 * report.mjs — the dashboard's data, and the static report (`pxsig report`).
 *
 *   pxsig serve                                   # live, every project: http://127.0.0.1:6070
 *   pxsig report [--project x] [--out dir]        # static: one project, opens from disk
 *
 * `buildData(P)` gathers one project's output (<store>/reports/*.json, the run history, review
 * decisions); the server answers `/__pxsig/data?project=` with it. The dashboard itself ships
 * prebuilt in `dist/dashboard/` (see packages/dashboard).
 *
 * Producers: check.mjs and the server write check.json, review.json and history.ndjson; the
 * repository's research tools (scenarios, calibration, bench) write scenarios[-<suite>].json,
 * calibration[-<suite>].json, calibration-gate.json, calibration-detail.json and bench.json.
 * Every scenarios / calibration suite present is passed on, keyed by suite (`default` for the
 * unsuffixed file).
 *
 * `pxsig report` exits 2 on any error (no project, dashboard not built, unwritable output).
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { herePath } from './lib/machine.mjs';
import { shortPath } from './lib/paths.mjs';
import { readImage } from './lib/psig.mjs';
import { readJson, tailLines } from './lib/files.mjs';
import { manifestSource } from './lib/source.mjs';
import { byStory } from './lib/approvals/story.mjs';
import { PXSIG_VERSION, engineVersion, openProject } from './lib/workspace.mjs';
import { reactData } from './lib/react/data.mjs';
import { readRejections, withoutNotes } from './lib/rejections.mjs';
import { rejectionOptions } from './lib/rejections/packet.mjs';
import { rejectionPrompt } from './lib/rejections/prompt.mjs';
/** @import { Manifest, Project } from './types.js' */
/** @import { CheckReport } from './types/t5.js' */
/** @import { ReactLive } from './types/react.js' */
/** @import { Rejection, RejectionKind, RejectionsFile } from './types/rejections.js' */

const here = dirname(fileURLToPath(import.meta.url));
/**
 * The dashboard (index.html + assets/): the prebuilt one, or PXSIG_DASHBOARD_DIR (a dashboard
 * rebuilt on a project's own design system by `pxsig dashboard build`).
 */
export const prebuiltDashboardDir = resolve(here, '..', 'dist', 'dashboard');
export let dashboardDir = process.env.PXSIG_DASHBOARD_DIR
  ? resolve(process.env.PXSIG_DASHBOARD_DIR)
  : prebuiltDashboardDir;
/**
 * Serve or write another dashboard folder (`pxsig serve` picks one: lib/dashboard-dir.mjs).
 * @param {string} dir
 */
export function useDashboard(dir) {
  dashboardDir = dir;
}

/**
 * @param {Project} P
 * @param {number} [limit]
 */
function history(P, limit = 100) {
  const p = join(P.store.reports, 'history.ndjson');
  if (!existsSync(p)) return [];
  // The log grows with every check; only its tail is read.
  return tailLines(p, limit)
    .map((l) => {
      try {
        // A line the engine wrote (`--history`): `rows` maps an id to `[pass, …]`.
        const r =
          /** @type {{ at?: string, summary?: unknown, rows?: Record<string, unknown[]> }} */ (
            JSON.parse(l)
          );
        return {
          at: r.at,
          summary: r.summary,
          failedIds: Object.entries(r.rows ?? {})
            .filter(([, v]) => v[0] === 0)
            .map(([k]) => k),
        };
      } catch {
        return null;
      }
    })
    .filter(Boolean);
}

/**
 * Every `<prefix>.json` / `<prefix>-<suite>.json` in the reports folder, keyed by suite.
 * @param {Project} P
 * @param {string} prefix
 * @param {string[]} [exclude]
 */
function suites(P, prefix, exclude = []) {
  /** @type {Record<string, unknown>} */
  const out = {};
  /** @type {string[]} */
  let names = [];
  try {
    names = readdirSync(P.store.reports);
  } catch {
    return out;
  }
  const re = new RegExp(`^${prefix}(?:-([a-z0-9][a-z0-9-]*))?\\.json$`, 'i');
  for (const n of names.sort()) {
    const m = n.match(re);
    if (!m || exclude.includes(m[1])) continue;
    const v = readJson(join(P.store.reports, n));
    if (v) out[m[1] ?? 'default'] = v;
  }
  return out;
}

/**
 * This pxsig's UI contract version, from the lock shipped with the dashboard source; null without it.
 * @returns {string | null}
 */
export function uiContractVersion() {
  for (const d of [join(here, '..', 'dashboard'), join(here, '..', '..', 'dashboard')])
    try {
      // contract-lock.json, generated by scripts/ui.mjs: `version` is a string.
      return /** @type {{ version: string }} */ (
        JSON.parse(readFileSync(join(d, 'src', 'ui', 'contract-lock.json'), 'utf8'))
      ).version;
    } catch {
      // not in this layout
    }
  return null;
}

/**
 * One project's dashboard data. `base` is the URL prefix of the project's files: `/p/<name>/`
 * when served, `./` for a static report; `live`, the server's React state (serve/react.mjs).
 * @param {Project} P
 * @param {{ base?: string, live?: ReactLive | null }} [opts]
 */
export function buildData(P, { base = `/p/${encodeURIComponent(P.name)}/`, live = null } = {}) {
  // The manifest pxsig wrote (docs/spec.md section 6).
  const manifest = /** @type {Manifest | null} */ (readJson(P.manifestPath())) ?? {
    stories: [],
  };
  const read = (/** @type {string} */ name) => readJson(join(P.store.reports, `${name}.json`));
  const check = /** @type {CheckReport | null} */ (read('check'));
  // The React analysis: always when served, else only with results to show (lib/react/data.mjs).
  const react = reactData(P, { check, live });
  return {
    generatedAt: new Date().toISOString(),
    project: P.name,
    /** The project switcher's name for it: the project's `label`, else its name. */
    label: P.label ?? P.name,
    /** The scope the title names after "pxsig •": the workspace's label, else the project's. */
    scope: P.scope,
    /** What drew the page, for the top bar's tooltip and the Help section. */
    versions: {
      pxsig: PXSIG_VERSION,
      engine: engineVersion(P.rustBin),
      contract: uiContractVersion(),
    },
    store: relative(P.workspaceRoot, P.store.root),
    check,
    ...(react ? { react } : {}),
    gateCalibration: read('calibration-gate'),
    /** scenarios.json → `default`, scenarios-<suite>.json → `<suite>`. */
    scenarioSuites: suites(P, 'scenarios'),
    /** calibration[-<suite>].json, except the gate and detail calibrations (their own fields). */
    calibrationSuites: suites(P, 'calibration', ['gate', 'detail']),
    detailCalibration: read('calibration-detail'),
    bench: read('bench'),
    history: history(P),
    review: read('review') ?? {},
    /** Whether the inspector offers Approve story (`approvals.byStory`, off by default). */
    approvals: { byStory: byStory(P.config) },
    a11yReview: read('a11y-review') ?? {},
    /** What the dashboard asks on Reject: the reason, unless `rejections.note.ask` is false. */
    settings: { rejections: { note: { ask: rejectionOptions(P.config).noteAsk } } },
    /**
     * The open rejections, with their reasons (lib/rejections.mjs) and each one's paragraph for an
     * assistant (Copy for an agent); a static report has none.
     */
    rejections: withPrompts(P, readRejections(P)),
    integrity: read('integrity'),
    storybook: { baseUrl: P.storybook.url },
    /** `dashboard-screens`: pxsig's own screens, with no Storybook to link to or re-check in. */
    source: manifestSource(P.manifestPath()),
    // renders/base/<id>.png is the baseline image inside each .psig, served (or written) by id.
    paths: {
      diffRoot: `${base}diffs/`,
      renders: `${base}renders/`,
      baselines: `${base}baselines/`,
      /** The rejection packets (`/p/<project>/reports/rejected/`, served to this origin only). */
      rejected: `${base}reports/rejected/`,
    },
    sigs: Object.fromEntries(
      (manifest.stories ?? []).map((s) => [s.id, `${base}sig/${encodeURIComponent(s.id)}`])
    ),
  };
}

/**
 * The open rejections, each with `prompt`: the words Copy for an agent copies, the same the
 * packet, the CLI and MCP use (lib/rejections/prompt.mjs).
 * @param {Project} P
 * @param {RejectionsFile} open
 * @returns {Record<RejectionKind, Record<string, Rejection & { prompt: string }>>}
 */
function withPrompts(P, open) {
  const store = relative(P.workspaceRoot, P.store.root);
  /** @param {RejectionKind} kind */
  const each = (kind) =>
    Object.fromEntries(
      Object.entries(open[kind]).map(([id, r]) => [
        id,
        {
          ...r,
          prompt: rejectionPrompt({
            id,
            project: P.name,
            kind,
            note: r.note,
            store,
            packet: r.packet,
          }),
        },
      ])
    );
  return { visual: each('visual'), a11y: each('a11y') };
}

/**
 * index.html with the data inlined (static) or with the placeholder left for the server.
 * @param {Omit<ReturnType<typeof buildData>, 'rejections'>} data
 */
export function pageWithData(data) {
  const html = readFileSync(join(dashboardDir, 'index.html'), 'utf8');
  const json = JSON.stringify({ ...data, static: true }).replace(/</g, '\\u003c');
  return html.replace(
    /<script id="pxsig-data">[\s\S]*?<\/script>|<!--pxsig:data-->/,
    `<script id="pxsig-data">window.PXSIG=${json}</script>`
  );
}

/**
 * Write a static report for one project into `out`: the app, the data and the images it shows.
 * @param {Project} P
 * @param {string} out
 */
export function writeStaticReport(P, out) {
  if (!existsSync(join(dashboardDir, 'index.html')))
    throw new Error(`the dashboard is not built (${shortPath(P.workspaceRoot, dashboardDir)})`);
  mkdirSync(join(out, 'assets'), { recursive: true });
  for (const f of readdirSync(join(dashboardDir, 'assets')))
    copyFileSync(join(dashboardDir, 'assets', f), join(out, 'assets', f));
  // A static report is made to be shared: the reasons belong to the live session.
  const { rejections: _open, ...shared } = buildData(P, { base: './' });
  const data = {
    ...shared,
    // review.json and a11y-review.json are pxsig's own files: entry id → decision.
    review: withoutNotes(/** @type {Record<string, { note?: string }>} */ (shared.review)),
    a11yReview: withoutNotes(/** @type {Record<string, { note?: string }>} */ (shared.a11yReview)),
  };
  writeFileSync(join(out, 'index.html'), pageWithData(data));
  // Images: latest renders and diffs as they are; baseline images out of their .psig files.
  const copyDir = (/** @type {string} */ from, /** @type {string} */ to) => {
    if (!existsSync(from)) return;
    mkdirSync(to, { recursive: true });
    for (const f of readdirSync(from))
      if (/\.(png|html)$/.test(f)) copyFileSync(join(from, f), join(to, f));
  };
  copyDir(P.store.latest, join(out, 'renders', 'latest'));
  copyDir(P.store.diffLatest, join(out, 'diffs', 'latest'));
  mkdirSync(join(out, 'renders', 'base'), { recursive: true });
  // The manifest pxsig wrote (docs/spec.md section 6).
  const manifest = /** @type {Manifest | null} */ (readJson(P.manifestPath())) ?? {
    stories: [],
  };
  let images = 0;
  for (const e of manifest.stories) {
    const img = readImage(resolve(P.workspaceRoot, e.sig));
    if (img) {
      writeFileSync(join(out, 'renders', 'base', `${e.id}.png`), img);
      images++;
    }
  }
  return { data, images };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { parseArgs, strFlag } = await import('./lib/args.mjs');
  const { flags } = parseArgs(process.argv.slice(2));
  try {
    const P = openProject({
      project: strFlag(flags, 'project'),
      workspace: strFlag(flags, 'workspace'),
    });
    const out = resolve(strFlag(flags, 'out') ?? join(P.store.reports, 'site'));
    const { images } = writeStaticReport(P, out);
    // Relative to the current folder: it opens from there, and an absolute path names the user.
    console.log(
      `[report] ${herePath(join(out, 'index.html'))} · project ${P.name} · ${images} baseline images`
    );
  } catch (e) {
    // openProject and the writes above throw an Error.
    console.error(`[report] ${/** @type {Error} */ (e).message}`);
    process.exit(2);
  }
}
