/**
 * A JSON file, or `fallback` when it is missing or does not parse. Callers name the shape of the
 * file they read.
 * @param {string} p
 * @param {unknown} [fallback]
 * @returns {unknown}
 */
const readJson = (p, fallback = null) => {
  try {
    return JSON.parse(readFileSync(p, 'utf8'));
  } catch {
    return fallback;
  }
};

/** What `pxsig init` writes into a new store. Run output stays out of git; baselines go in. */
export const STORE_GITIGNORE = `# pxsig run output (regenerated by every check)
renders/
diffs/
reports/
cache/
history/
trash/
`;
export const STORE_GITATTRIBUTES = `# .psig baselines are binary; git diff shows their header via: git config diff.psig.textconv "npx pxsig cat"
*.psig binary diff=psig
# Records keep LF on every OS, so a Windows checkout reads them byte for byte as written
*.json text eol=lf
*.ndjson text eol=lf
`;

export const PSIG_ATTRIBUTE = '*.psig binary diff=psig';

/**
 * Make sure `<root>/.gitattributes` marks `*.psig` binary with the `psig` diff driver. Appends the
 * line when no line already sets attributes for `*.psig`; idempotent. Returns the path when it wrote.
 * @param {string} root
 * @returns {string | null}
 */
export function ensureGitattributes(root) {
  const p = join(root, '.gitattributes');
  const text = existsSync(p) ? readFileSync(p, 'utf8') : '';
  if (text.split(/\r?\n/).some((l) => /^\s*\*\.psig\s/.test(l))) return null;
  const sep = text && !text.endsWith('\n') ? '\n' : '';
  appendFileSync(
    p,
    `${sep}# pxsig baselines: binary; \`git config diff.psig.textconv "npx pxsig cat"\` shows their header in diffs\n${PSIG_ATTRIBUTE}\n`
  );
  return p;
}

/**
 * The layout a project resolves to, from its config and the workspace defaults.
 * @param {InitConfig} cfg
 * @param {string | null} workspaceRoot
 * @returns {string}
 */
const layoutOf = (cfg, workspaceRoot) =>
  cfg.store?.layout ??
  (workspaceRoot
    ? // the workspace file, as written: its defaults are a project config layer
      /** @type {WorkspaceFile & { defaults?: InitConfig }} */ (
        readJson(join(workspaceRoot, WORKSPACE_FILE), {})
      )?.defaults?.store?.layout
    : null) ??
  'package';

/**
 * Set a package up: its config (unless one exists), its store and, in a monorepo, its entry in
 * the workspace file. A colocated project also gets `*.psig binary diff=psig` in the root
 * `.gitattributes` (the workspace's, else its own). Returns what it wrote.
 * @param {{ dir: string, name?: string | null, label?: string | null, srcRoot?: string, storybookUrl?: string | null, storybookConfigDir?: string | null, workspaceRoot?: string | null, layout?: string | null }} opts
 * @returns {string[]}
 */
export function initProject({
  dir,
  name = null,
  label = null,
  srcRoot = 'src',
  storybookUrl = null,
  storybookConfigDir = null,
  workspaceRoot = null,
  layout = null,
}) {
  /** @type {string[]} */
  const wrote = [];
  const configPath = join(dir, CONFIG_FILE);
  if (layout && !['package', 'colocated'].includes(layout))
    throw new SetupError('--layout must be "package" or "colocated"');
  if (label != null && (!label.trim() || label.trim().length > 60))
    throw new SetupError('--label must be text of 1 to 60 characters');
  if (!existsSync(configPath)) {
    /** @type {InitConfig} */
    const cfg = {
      version: 1,
      ...(name ? { name } : {}),
      ...(label?.trim() ? { label: label.trim() } : {}),
      srcRoot,
    };
    if (storybookUrl || storybookConfigDir)
      cfg.storybook = {
        ...(storybookUrl ? { url: storybookUrl } : {}),
        ...(storybookConfigDir ? { configDir: storybookConfigDir } : {}),
      };
    if (layout) cfg.store = { layout };
    writeJson(configPath, cfg, { pretty: true });
    wrote.push(configPath);
  }
  // the project's config, as written (by this function or by hand)
  const cfg = /** @type {InitConfig} */ (readJson(configPath, {}));
  const store = resolve(dir, cfg.store?.dir ?? '.pxsig');
  mkdirSync(store, { recursive: true });
  for (const [file, text] of [
    ['.gitignore', STORE_GITIGNORE],
    ['.gitattributes', STORE_GITATTRIBUTES],
  ]) {
    const p = join(store, file);
    if (!existsSync(p)) {
      writeFileSync(p, text);
      wrote.push(p);
    }
  }
  if (workspaceRoot && resolve(workspaceRoot) !== resolve(dir)) {
    const wsFile = join(workspaceRoot, WORKSPACE_FILE);
    const ws = /** @type {WorkspaceFile} */ (readJson(wsFile, { version: 1, projects: {} }));
    const rel = toPosix(relative(workspaceRoot, dir));
    if (!Object.values(ws.projects ?? {}).includes(rel)) {
      const key = cfg.name ?? name ?? basename(dir);
      if (ws.projects?.[key])
        throw new SetupError(`${wsFile} already has a project named "${key}": pass --name`);
      ws.projects = { ...ws.projects, [key]: rel };
      writeJson(wsFile, ws, { pretty: true });
      wrote.push(wsFile);
    }
  }
  if (layoutOf(cfg, workspaceRoot) === 'colocated') {
    const ga = ensureGitattributes(workspaceRoot ?? dir);
    if (ga) wrote.push(ga);
  }
  return wrote;
}

/**
 * A suite's entry options: `{ modes: [...] }` means exactly those modes.
 * @param {Project} P
 * @param {string | null} suite
 * @returns {{ addModes?: string[], modes?: string[] }}
 */
function suiteOptions(P, suite) {
  if (!suite) return {};
  const s = P.config.suites?.[suite];
  if (!s)
    throw new SetupError(
      `project "${P.name}" has no suite "${suite}" (suites: ${Object.keys(P.config.suites ?? {}).join(', ') || 'none'})`
    );
  const modes = s.modes ?? s.addModes ?? [];
  const unknown = modes.filter((m) => !P.modes[m]);
  if (unknown.length)
    throw new SetupError(`suite "${suite}" names unknown modes: ${unknown.join(', ')}`);
  return { addModes: modes, modes };
}

/**
 * Build (or rebuild) a manifest from the running Storybook. Existing entries keep their baseline
 * path; new ones get the layout's path and no baseline. Returns { manifest, added, removed, skipped }.
 * @param {Project} P
 * @param {{ suite?: string | null, write?: boolean }} [opts]
 * @returns {Promise<BuiltManifest>}
 */
export async function buildManifest(P, { suite = null, write = true } = {}) {
  const ctx = resolveContext(P, { manifestPath: P.manifestPath(suite) });
  const idx = await loadStoryIndex(ctx);
  if (idx.source !== 'storybook')
    throw new SetupError(
      `Storybook is needed to read each story's parameters: ${idx.storybook.error} (${idx.storybook.url})`
    );
  const nonVisual = new Set(P.config.nonVisual ?? []);
  const stories = idx.stories.filter((s) => {
    const c = componentOf(ctx, s.importPath);
    return c != null && !nonVisual.has(c.split('/')[0]);
  });
  if (!stories.length)
    throw new SetupError(
      `no stories in ${toPosix(relative(P.workspaceRoot, P.srcRoot))} in the Storybook index (check srcRoot and storybook.configDir)`
    );
  const params = await harvestParameters(
    P,
    P.storybook.url,
    stories.map((s) => s.id)
  );
  // the manifest pxsig wrote last time, if any
  const before = /** @type {{ stories?: ManifestEntry[] }} */ (
    readJson(ctx.manifestPath, { stories: [] })
  );
  const known = new Map((before.stories ?? []).map((e) => [e.id, e]));
  const list = stories.map((s) => ({
    id: s.id,
    importPath: s.importPath,
    sigFor: (/** @type {string} */ key) => known.get(key)?.sig ?? P.sigFor(key, s.importPath),
  }));
  const { entries, skipped } = expandEntries(entryConfig(P), list, params, suiteOptions(P, suite));
  const ids = new Set(entries.map((e) => e.id));
  const manifest = {
    version: 2,
    project: P.name,
    ...(suite ? { suite } : {}),
    stories: entries,
    skipped,
  };
  if (write) writeJsonAtomic(ctx.manifestPath, manifest, { pretty: true });
  return {
    manifest,
    path: ctx.manifestPath,
    added: entries.filter((e) => !known.has(e.id)).map((e) => e.id),
    removed: [...known.keys()].filter((id) => !ids.has(id)),
    skipped,
  };
}

/**
 * The resolved config, with the files it came from and, per key, the layer that set it.
 * @param {Project} P
 * @returns {DescribedConfig}
 */
export function describeConfig(P) {
  return {
    sources: P.configSources,
    project: P.name,
    label: P.label,
    workspace: P.workspaceRoot,
    workspaceFile: P.workspaceFile,
    configFile: P.configPath,
    root: P.root,
    srcRoot: P.srcRoot,
    storybook: P.storybook,
    store: P.store,
    modes: P.modes,
    defaultMode: P.defaultMode,
    modesByDefault: P.modesByDefault,
    affects: P.affects,
    rustBin: P.rustBin,
    config: P.config,
  };
}

// --- migration from the pre-0.2 layout -----------------------------------------------------------------

/**
 * The pre-0.2 layout's manifests (main and per suite), under the legacy folder's `js/`.
 * @param {string} from
 * @returns {{ suite: string | null, path: string }[]}
 */
function legacyManifests(from) {
  const dir = join(from, 'js');
  if (!existsSync(join(dir, 'pxsig.manifest.json')))
    throw new SetupError(`no legacy manifest at ${join(dir, 'pxsig.manifest.json')}`);
  return readdirSync(dir)
    .filter((n) => /^pxsig\.manifest(\.[a-z0-9-]+)?\.json$/.test(n))
    .sort()
    .map((n) => ({
      suite: n.match(/^pxsig\.manifest\.([a-z0-9-]+)\.json$/)?.[1] ?? null,
      path: join(dir, n),
    }));
}

/** Per-entry fields a manifest keeps; the settings the old manifest repeated come from config now. */
/** @type {(keyof ManifestEntry)[]} */
const ENTRY_KEYS = [
  'id',
  'story',
  'mode',
  'state',
  'sig',
  'importPath',
  'globals',
  'colorScheme',
  'viewport',
  'browser',
  'grid',
  'gate',
  'detail',
  'ignore',
  'interaction',
  'delay',
  'target',
  'play',
  'a11y',
];
/**
 * @param {ManifestEntry} e
 * @returns {ManifestEntry} a legacy entry's manifest keys (the old pxsig wrote every required one)
 */
const pick = (e) =>
  /** @type {ManifestEntry} */ (
    /** @type {unknown} */ (
      Object.fromEntries(ENTRY_KEYS.filter((k) => e[k] !== undefined).map((k) => [k, e[k]]))
    )
  );

/**
 * Plan (and with `apply`, run) the move of a legacy store into the project's store. The legacy
 * folder is only read. `verify` re-checks the legacy renders against old and new baselines with
 * the Rust engine and requires identical results.
 * @param {Project} P
 * @param {{ from?: string, apply?: boolean, verify?: boolean, log?: (message: string) => void }} [opts]
 * @returns {MigratePlan}
 */
export function migrateLegacy(P, { from, apply = false, verify = true, log = () => {} } = {}) {
  // The CLI always passes `from`; without it, resolve throws as before.
  from = resolve(/** @type {string} */ (from));
  const manifests = legacyManifests(from);
  // `summary` is set below, before either return.
  const plan = /** @type {MigratePlan} */ (
    /** @type {Partial<MigratePlan>} */ ({
      from,
      to: P.store.root,
      manifests: [],
      pack: [],
      copies: [],
      problems: [],
    })
  );
  /** @type {Map<string, string>} */
  const outOf = new Map();
  for (const m of manifests) {
    // a manifest the pre-0.2 pxsig wrote (checked on the next line)
    const old = /** @type {LegacyManifest | null} */ (readJson(m.path));
    if (!old?.stories) {
      plan.problems.push(`${m.path} is not a manifest`);
      continue;
    }
    const target = P.manifestPath(m.suite);
    /** @type {ManifestEntry[]} */
    const stories = [];
    for (const e of old.stories) {
      const sigOld = resolve(P.workspaceRoot, e.sig);
      const sigNew = P.sigFor(e.id, e.importPath);
      const out = resolve(P.workspaceRoot, sigNew);
      if (outOf.has(out) && outOf.get(out) !== sigOld)
        plan.problems.push(`${e.id}: two baselines map to ${sigNew}`);
      outOf.set(out, sigOld);
      stories.push({ ...pick(e), sig: sigNew });
      if (!existsSync(sigOld)) continue; // unbaselined: nothing to pack
      const img = join(from, '.renders', 'base', `${e.id}.png`);
      plan.pack.push({
        sig: sigOld,
        out,
        image: m.suite ? null : existsSync(img) ? img : null,
        entry: { id: e.id, story: e.story ?? null, mode: e.mode ?? null, state: e.state ?? null },
      });
    }
    plan.manifests.push({
      suite: m.suite,
      from: m.path,
      to: target,
      entries: stories.length,
      manifest: {
        version: 2,
        project: P.name,
        ...(m.suite ? { suite: m.suite } : {}),
        stories,
        skipped: old.skipped ?? [],
      },
    });
  }
  // Matrix entries share no images with the main manifest: a suite entry gets its image only if
  // the legacy store had one under its own id.
  for (const item of plan.pack)
    if (!item.image) {
      const img = join(from, '.renders', 'base', `${item.entry.id}.png`);
      if (existsSync(img)) item.image = img;
    }
  /** @type {[string, string][]} */
  const files = [
    ['.baselines/a11y.json', P.store.a11y],
    ['.reports/review.json', join(P.store.reports, 'review.json')],
    ['.reports/history.ndjson', join(P.store.reports, 'history.ndjson')],
    ['.reports/check.json', join(P.store.reports, 'check.json')],
  ];
  for (const m of manifests)
    if (m.suite)
      files.push([
        `.reports/check-${m.suite}.json`,
        join(P.store.reports, `check-${m.suite}.json`),
      ]);
  for (const [src, dest] of files)
    if (existsSync(join(from, src))) plan.copies.push({ from: join(from, src), to: dest });
  const approvalsFrom = join(from, '.baselines', 'approvals.ndjson');
  plan.summary = {
    manifests: plan.manifests.map((m) => `${basename(m.to)}: ${m.entries} entries`),
    baselines: plan.pack.length,
    withImage: plan.pack.filter((x) => x.image).length,
    copies: plan.copies.length,
    approvals: existsSync(approvalsFrom),
    problems: plan.problems.length,
  };
  if (!apply || plan.problems.length) return plan;

  const existing = plan.pack.filter((x) => existsSync(x.out));
  if (existing.length)
    throw new SetupError(
      `${existing.length} baselines already exist in ${P.store.root} (first: ${existing[0].out}); migrate into an empty store`
    );
  mkdirSync(P.store.reports, { recursive: true });
  const planFile = join(P.store.reports, 'migrate-plan.json');
  writeFileSync(planFile, JSON.stringify(plan.pack));
  log(`packing ${plan.pack.length} baselines`);
  const r = spawnSync(P.rustBin, ['pack', '--plan', planFile, '--json'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (r.status !== 0) throw new SetupError(`pxsig pack failed: ${r.stderr || r.stdout}`);
  // the engine's `pack --json` report
  plan.packed = /** @type {{ summary?: unknown }} */ (JSON.parse(r.stdout)).summary;
  for (const m of plan.manifests) writeJsonAtomic(m.to, m.manifest, { pretty: true });
  for (const c of plan.copies) {
    mkdirSync(dirname(c.to), { recursive: true });
    copyFileSync(c.from, c.to);
  }
  // The approvals trail carries over, and one `migrated` line per baseline records the new file's
  // hash, so `pxsig approve verify` starts clean on the new store.
  if (existsSync(approvalsFrom)) copyFileSync(approvalsFrom, P.store.approvals);
  const at = new Date().toISOString();
  const lines = plan.pack.map((x) =>
    JSON.stringify({
      at,
      id: x.entry.id,
      by: 'pxsig migrate',
      via: 'migrate',
      batch: `migrate-${at.replace(/[:.]/g, '-')}`,
      reason: `moved from ${toPosix(relative(P.workspaceRoot, x.sig))}`,
      kind: null,
      gitHead: null,
      before: sha256(x.sig),
      after: sha256(x.out),
    })
  );
  for (const l of lines) appendLine(P.store.approvals, l);
  for (const [file, text] of [
    ['.gitignore', STORE_GITIGNORE],
    ['.gitattributes', STORE_GITATTRIBUTES],
  ])
    if (!existsSync(join(P.store.root, file))) writeFileSync(join(P.store.root, file), text);
  if (P.store.layout === 'colocated') plan.gitattributes = ensureGitattributes(P.workspaceRoot);
  if (verify) plan.verify = verifyMigration(P, plan, from, log);
  return plan;
}

/**
 * Check the legacy latest renders against the old baselines and the new ones, with the same
 * engine, gate and settings. Every entry must get the same verdict, metrics and detail result.
 * @param {Project} P
 * @param {{ manifests: MigrateManifest[] }} plan
 * @param {string} from
 * @param {(message: string) => void} [log]
 * @returns {MigrateVerify[]}
 */
export function verifyMigration(P, plan, from, log = () => {}) {
  const renders = join(from, '.renders', 'latest');
  /** @type {MigrateVerify[]} */
  const out = [];
  for (const m of plan.manifests) {
    const scratch = join(P.store.reports, '.migrate-verify', m.suite ?? 'main');
    mkdirSync(scratch, { recursive: true });
    const oldRun = join(scratch, 'old.json');
    const newRun = join(scratch, 'new.json');
    // the legacy manifest `migrateLegacy` read (it has `stories`)
    const oldManifest = {
      ...m.manifest,
      stories: /** @type {Required<LegacyManifest>} */ (readJson(m.from)).stories,
    };
    writeFileSync(oldRun, JSON.stringify(runManifest(P, oldManifest)));
    writeFileSync(newRun, JSON.stringify(runManifest(P, m.manifest)));
    /**
     * @param {string} manifest
     * @param {string} _dir
     * @returns {Map<string, EngineVerdict>}
     */
    const check = (manifest, _dir) => {
      const r = spawnSync(
        P.rustBin,
        [
          'check',
          '--manifest',
          manifest,
          '--png-dir',
          renders,
          '--root',
          P.workspaceRoot,
          '--json',
          '--artifacts',
          'none',
        ],
        { encoding: 'utf8', maxBuffer: 512 * 1024 * 1024 }
      );
      if (r.status === 2)
        throw new SetupError(`verification check failed: ${r.stderr || r.stdout}`);
      // the engine's `check --json` report
      return new Map(
        /** @type {{ results: EngineVerdict[] }} */ (JSON.parse(r.stdout)).results.map((x) => [
          x.id,
          x,
        ])
      );
    };
    log(
      `verifying ${m.entries} entries${m.suite ? ` (suite ${m.suite})` : ''} against ${toPosix(relative(P.workspaceRoot, renders))}`
    );
    const a = check(oldRun, join(scratch, 'old'));
    const b = check(newRun, join(scratch, 'new'));
    /** @param {EngineVerdict | undefined} x */
    const key = (x) => JSON.stringify([x?.pass, x?.metrics, x?.detail, x?.error ? 'error' : null]);
    const differ = [...a.keys()].filter((id) => key(a.get(id)) !== key(b.get(id)));
    out.push({
      suite: m.suite,
      entries: a.size,
      passOld: [...a.values()].filter((x) => x.pass === true).length,
      passNew: [...b.values()].filter((x) => x.pass === true).length,
      differ: differ.length,
      sample: differ.slice(0, 10),
    });
  }
  return out;
}
