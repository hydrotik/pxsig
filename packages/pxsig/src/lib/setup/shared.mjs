/**
 * What setup.mjs and setup/migrate.mjs share: the JSON reader, and the git files a store and a
 * repository get.
 */
import { appendFileSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** The shared JSON reader (lib/files.mjs): a missing, broken or UTF-16 file gives `fallback`. */
export { readJson } from '../files.mjs';

/** What `pxsig init` writes into a new store. Run output stays out of git; baselines go in. */
export const STORE_GITIGNORE = `# pxsig run output (regenerated by every check)
renders/
diffs/
reports/
cache/
history/
trash/
`;
export const STORE_GITATTRIBUTES = `# .psig baselines are binary; git diff shows their header via: git config diff.psig.textconv "npx pxsig cat"
*.psig binary diff=psig
# Records keep LF on every OS, so a Windows checkout reads them byte for byte as written
*.json text eol=lf
*.ndjson text eol=lf
`;

export const PSIG_ATTRIBUTE = '*.psig binary diff=psig';

/**
 * Make sure `<root>/.gitattributes` marks `*.psig` binary with the `psig` diff driver. Appends the
 * line when no line already sets attributes for `*.psig`; idempotent. Returns the path when it wrote.
 * @param {string} root
 * @returns {string | null}
 */
export function ensureGitattributes(root) {
  const p = join(root, '.gitattributes');
  const text = existsSync(p) ? readFileSync(p, 'utf8') : '';
  if (text.split(/\r?\n/).some((l) => /^\s*\*\.psig\s/.test(l))) return null;
  const sep = text && !text.endsWith('\n') ? '\n' : '';
  appendFileSync(
    p,
    `${sep}# pxsig baselines: binary; \`git config diff.psig.textconv "npx pxsig cat"\` shows their header in diffs\n${PSIG_ATTRIBUTE}\n`
  );
  return p;
}
